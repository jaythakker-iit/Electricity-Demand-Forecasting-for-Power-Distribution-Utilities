        plt.figure(figsize=(9, 5))

        sns.boxplot(
            data=df,
            x="Weather_Condition",
            y="MW"
        )

        plt.title("Electricity Demand by Weather Condition")
        plt.xlabel("Weather Condition")
        plt.ylabel("Demand (MW)")
        plt.xticks(rotation=30)
        plt.tight_layout()
        plt.show()


