# 4. ELECTRICITY DEMAND EDA
# ============================================================

def demand_eda(df):

    print("\n[4] ELECTRICITY DEMAND EDA")
    print("-" * 40)

    # Convert timestamp and sort
    df = df.dropna(subset=["Datetime"]).copy()
    df = df.sort_values("Datetime")

    df = df.set_index("Datetime")

    # Demand statistics
    print(f"Average demand : {df['MW'].mean():.2f} MW")
    print(f"Maximum demand : {df['MW'].max():.2f} MW")
    print(f"Minimum demand : {df['MW'].min():.2f} MW")

    peak_time = df["MW"].idxmax()
    minimum_time = df["MW"].idxmin()

    print(f"Peak demand time    : {peak_time}")
    print(f"Minimum demand time : {minimum_time}")

    # Historical demand
    plt.figure(figsize=(15, 5))

    plt.plot(
        df.index,
        df["MW"],
        linewidth=0.8
    )

    plt.title("Historical Electricity Demand")
    plt.xlabel("Date")
    plt.ylabel("Demand (MW)")
    plt.tight_layout()
    plt.show()

    # Time features for EDA only
    df["Hour"] = df.index.hour
    df["Day_of_Week"] = df.index.dayofweek
    df["Month"] = df.index.month

    # Hourly pattern
    plt.figure(figsize=(10, 5))

    sns.boxplot(
        data=df,
        x="Hour",
        y="MW"
    )

    plt.title("Electricity Demand by Hour")
    plt.xlabel("Hour of Day")
    plt.ylabel("Demand (MW)")
    plt.tight_layout()
    plt.show()

    # Day-of-week pattern
    plt.figure(figsize=(10, 5))

    sns.boxplot(
        data=df,
        x="Day_of_Week",
        y="MW"
    )

    plt.title("Electricity Demand by Day of Week")
    plt.xlabel("Day of Week (0 = Monday)")
    plt.ylabel("Demand (MW)")
    plt.tight_layout()
    plt.show()

    # Monthly pattern
    plt.figure(figsize=(10, 5))

    sns.boxplot(
        data=df,
        x="Month",
        y="MW"
    )

    plt.title("Electricity Demand by Month")
    plt.xlabel("Month")
    plt.ylabel("Demand (MW)")
    plt.tight_layout()
    plt.show()

    return df


