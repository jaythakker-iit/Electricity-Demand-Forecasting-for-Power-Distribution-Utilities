def weather_eda(df):

    print("\n[5] WEATHER EDA")
    print("-" * 40)

    if "Temp" in df.columns:

        print(
            f"Temperature range: "
            f"{df['Temp'].min():.1f} to "
            f"{df['Temp'].max():.1f}"
        )

        plt.figure(figsize=(7, 5))

