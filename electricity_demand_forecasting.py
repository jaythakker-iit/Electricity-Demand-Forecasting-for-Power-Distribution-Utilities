# ============================================================

def calendar_eda(df):

    print("\n[6] HOLIDAY & FESTIVAL EDA")
    print("-" * 40)

    if "Holiday_Type" in df.columns:

        print("\nHoliday distribution:")
        print(df["Holiday_Type"].value_counts(dropna=False))

        plt.figure(figsize=(9, 5))

        sns.boxplot(
            data=df,
            x="Holiday_Type",
            y="MW"
        )

        plt.title("Electricity Demand by Holiday Type")
        plt.xlabel("Holiday Type")
        plt.ylabel("Demand (MW)")
        plt.xticks(rotation=30)
        plt.tight_layout()
        plt.show()

    if "Festival_Name" in df.columns:

        print("\nFestival distribution:")
        print(df["Festival_Name"].value_counts(dropna=False).head(15))

        # Only show the most frequent festival categories
        top_festivals = (
            df["Festival_Name"]
            .value_counts()
            .head(10)
            .index
        )

        festival_df = df[
            df["Festival_Name"].isin(top_festivals)
        ]

        if len(festival_df) > 0:

            plt.figure(figsize=(10, 5))

            sns.boxplot(
                data=festival_df,
                x="Festival_Name",
                y="MW"
            )

            plt.title("Electricity Demand for Major Festival Categories")
            plt.xlabel("Festival")
            plt.ylabel("Demand (MW)")
            plt.xticks(rotation=45)
            plt.tight_layout()
            plt.show()


